import type { ImxGateReport } from "./types.js";

const MARK: Record<string, string> = { blocking: "FAIL", warning: "WARN", info: "INFO" };

export function toConsole(r: ImxGateReport): string {
  const lines: string[] = [];
  lines.push("");
  lines.push("IMX GATE (G2) — Civil 3D export check");
  lines.push("─".repeat(72));
  lines.push(`File          ${r.file}`);
  lines.push(`Size          ${(r.fileBytes / 1024 / 1024).toFixed(1)} MB`);
  lines.push(`IMX version   ${r.imxVersion ?? "(none)"}`);
  lines.push(`Declared CRS  ${r.declaredCrs ?? "(none)"}`);
  lines.push("");

  for (const f of r.findings) {
    const tag = f.repaired ? "FIXED" : MARK[f.severity];
    lines.push(`[${tag}] ${f.ruleId} ${f.rule}`);
    for (const chunk of wrap(f.message, 68)) lines.push(`        ${chunk}`);
    lines.push("");
  }

  if (r.stats.regions.length) {
    lines.push("Corridor regions");
    lines.push("─".repeat(72));
    lines.push(pad("region", 26) + pad("span (m)", 12) + pad("sections", 10) + "max gap");
    for (const g of r.stats.regions) {
      lines.push(
        pad(g.name, 26) +
          pad(g.lengthM.toFixed(2), 12) +
          pad(String(g.sectionCount), 10) +
          (g.maxStationGapM === null ? "-" : `${g.maxStationGapM.toFixed(2)} m`),
      );
    }
    lines.push("");
  }

  if (r.repairedFile) {
    lines.push(`Repaired copy written: ${r.repairedFile}`);
    lines.push(`Records repaired:      ${r.repairedCount}`);
    lines.push("");
  }

  lines.push("─".repeat(72));
  lines.push(
    r.ok
      ? `PASS — ${r.warningCount} warning(s). Safe to import.`
      : `FAIL — ${r.blockingCount} blocking, ${r.warningCount} warning(s). Do not import yet.`,
  );
  lines.push("");
  return lines.join("\n");
}

export function toMarkdown(r: ImxGateReport): string {
  const out: string[] = [];
  out.push(`# IMX Gate (G2) — ${r.file.split(/[\\/]/).pop()}`);
  out.push("");
  out.push(`**Result** ${r.ok ? "PASS" : "FAIL"} · ${r.blockingCount} blocking · ${r.warningCount} warning · ${r.repairedCount} repaired`);
  out.push(`**Generated** ${r.generatedAt} · **IMX version** ${r.imxVersion ?? "(none)"} · **CRS** ${r.declaredCrs ?? "(none)"}`);
  out.push("");

  if (r.repairedFile) {
    out.push(`**Repaired copy** \`${r.repairedFile}\` — import this file, not the original.`);
    out.push("");
  }

  out.push("## Findings");
  out.push("");
  if (!r.findings.length) {
    out.push("No findings.");
  }
  for (const f of r.findings) {
    const tag = f.repaired ? "REPAIRED" : f.severity.toUpperCase();
    out.push(`### ${f.ruleId} — ${f.rule} · ${tag}`);
    out.push("");
    out.push(f.message);
    out.push("");
  }

  out.push("## Corridor regions");
  out.push("");
  out.push("| Region | Baseline | Alignment | Span (m) | Sections | Max gap (m) | Assembly | Subassemblies |");
  out.push("|---|---|---|---|---|---|---|---|");
  for (const g of r.stats.regions) {
    out.push(
      `| ${g.name} | ${g.baseline} | ${g.alignment ?? "—"} | ${g.lengthM.toFixed(2)} | ${g.sectionCount} | ` +
        `${g.maxStationGapM === null ? "—" : g.maxStationGapM.toFixed(2)} | ${g.assemblyName ?? "—"} | ` +
        `${g.subassemblyCount ?? "—"} |`,
    );
  }
  out.push("");

  if (r.stats.extent) {
    const e = r.stats.extent;
    out.push("## Road extent (source units)");
    out.push("");
    out.push(`E ${e.minX.toFixed(2)} … ${e.maxX.toFixed(2)} · N ${e.minY.toFixed(2)} … ${e.maxY.toFixed(2)} · Z ${e.minZ.toFixed(2)} … ${e.maxZ.toFixed(2)}`);
    out.push("");
  }

  out.push("---");
  out.push("");
  out.push("*Generated by `@infraworks/imx-gate`. Not for issue — internal technical check.*");
  return out.join("\n");
}

function pad(s: string, n: number): string {
  return (s.length > n - 1 ? `${s.slice(0, n - 2)}…` : s).padEnd(n);
}

function wrap(text: string, width: number): string[] {
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let cur = "";
  for (const w of words) {
    if (cur.length + w.length + 1 > width) {
      lines.push(cur);
      cur = w;
    } else {
      cur = cur ? `${cur} ${w}` : w;
    }
  }
  if (cur) lines.push(cur);
  return lines;
}
